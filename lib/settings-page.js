  ':root{color-scheme:light dark}',
  '*{box-sizing:border-box}',
  'body{margin:0;padding:20px 24px;font:13px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,"Helvetica Neue",Arial,"PingFang SC","Microsoft YaHei",sans-serif;background:var(--dsw-alias-bg-base,#fff);color:var(--dsw-alias-label-primary,#1b1b1f)}',
  'h1{margin:0 0 4px;font-size:16px;font-weight:600}',
  '.sub{color:var(--dsw-alias-label-tertiary,#8a8a8e);margin-bottom:14px}',
  '.bar{display:flex;flex-wrap:wrap;gap:8px;align-items:center;margin:10px 0 14px}',
  'button{font:inherit;padding:5px 10px;border-radius:6px;border:1px solid var(--dsw-alias-border-l1,#d9d9de);background:var(--dsw-alias-bg-module-platform,#f5f5f7);color:inherit;cursor:pointer}',
  'button:disabled{opacity:.5;cursor:default}',
  'button.primary{background:#2f6feb;border-color:#2f6feb;color:#fff}',
  'button.danger{color:#c02a2a;border-color:#e0b4b4}',
  'table{width:100%;border-collapse:collapse;font-size:12.5px}',
