  '.pill.bad{background:#fdeaea;color:#c02a2a;border-color:#f0c2c2}',
  '.pill.unk{background:#f4f4f6;color:#6b6b73;border-color:#e2e2e7}',
  '.pill.warn{background:#fff5e0;color:#96650a;border-color:#f0dcae}',
  '.pill.managed{background:#e8f0fe;color:#1a56c4;border-color:#c2d5fb}',
